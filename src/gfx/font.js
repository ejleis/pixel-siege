const SPACE = ['...', '...', '...', '...', '...'];
const glyph = (ch) => GLYPHS[ch] || SPACE;

export function textWidth(text, scale = 1) {
  let w = 0;
  for (const ch of String(text).toUpperCase()) w += glyph(ch)[0].length + 1;
  return Math.max(0, w - 1) * scale;
}

export function drawText(ctx, text, x, y, { color = '#f4f4f4', scale = 1, align = 'left', shadow = '#1a1c2c' } = {}) {
  const str = String(text).toUpperCase();
  const w = textWidth(str, scale);
  let sx = align === 'center' ? x - w / 2 : align === 'right' ? x - w : x;
  sx = Math.round(sx);
  const sy = Math.round(y);
  if (shadow) drawRaw(ctx, str, sx + scale, sy + scale, shadow, scale);
  drawRaw(ctx, str, sx, sy, color, scale);
}

function drawRaw(ctx, str, x, y, color, s) {
  ctx.fillStyle = color;
  let cx = x;
  for (const ch of str) {
    const g = glyph(ch);
    for (let r = 0; r < 5; r++) {
      for (let c = 0; c < g[r].length; c++) {
        if (g[r][c] === '#') ctx.fillRect(cx + c * s, y + r * s, s, s);
      }
    }
    cx += (g[0].length + 1) * s;
  }
}
